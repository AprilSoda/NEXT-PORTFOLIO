// Returns { t, pick, fmt, locale }: t("key") for UI strings, pick({ en, ko }) for
// content, fmt(name) for a Notion format option
export function useT() {
  const { locale = "en" } = useRouter()
  const table = strings[locale] || strings.en
  const t = (key, fallback) => table[key] ?? strings.en[key] ?? fallback ?? key
  const pick = (value) =>
    value && typeof value === "object" ? value[locale] ?? value.en : value
  const fmt = (name) => (name ? t(`format.${name.toLowerCase()}`, name) : name)
  return { t, pick, fmt, locale }
}
